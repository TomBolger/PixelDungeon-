#!/bin/sh
# Build the dungeon bot (or a host test) against the watch game's own C sources.
#
#   ./build.sh                          -> build/deepbot   (the bot)
#   OUT=itemtest MAIN=tests/itemtest.c ./build.sh   -> build/itemtest
#   ./build.sh -DSOMETHING              extra compiler flags are passed through
#
# The game code is not copied: it is compiled straight from ../watch/src. Each code overlay becomes its own
# shared library (build/libovl_<name>.so) that is opened and closed like an overlay on the watch, so an
# overlay's static variables start from zero on every load, exactly as they do on the watch.
set -e
cd "$(dirname "$0")"
BOT=$(pwd)
WATCH=$(cd ../watch && pwd)
B=$BOT/build
mkdir -p "$B"
CFLAGS="-std=c99 -O2 -DOVL_HOST -D_DEFAULT_SOURCE -DPD_DATA_DIR=\"$WATCH/resources/data\" -I$BOT/src -I$B -I$WATCH/src/c -Wall -Wno-unused-function -Wno-unused-parameter -Wno-format-truncation -Wno-misleading-indentation -Wno-unused-variable -Wno-unused-but-set-variable -Wno-parentheses"

# 1. RESOURCE_ID_* numbers in package.json order (rewritten only when they change: overlays depend on it)
python3 - "$WATCH/package.json" "$B/res_ids.h" <<'PY'
import json, os, sys
m = json.load(open(sys.argv[1]))["pebble"]["resources"]["media"]
names = ["TEXT"] + [x["name"] for x in m if x["name"] != "TEXT"]
t = "#pragma once\nenum { " + ", ".join(f"RESOURCE_ID_{n} = {i + 1}" for i, n in enumerate(names)) + " };\n"
if not os.path.exists(sys.argv[2]) or open(sys.argv[2]).read() != t: open(sys.argv[2], "w").write(t)
PY

# 2. One shared library per game overlay (UI-only overlays are not needed off the watch), rebuilt when a source changes
OV=""
for d in $(ls "$WATCH/src/ovl"); do
  case $d in snd|ui|uiw|bag|sheet) continue;; esac
  OV="$OV $d"
  so="$B/libovl_$d.so"; srcs=$(ls "$WATCH/src/ovl/$d"/*.c)
  need=0; [ -f "$so" ] || need=1
  for f in "$WATCH/src/ovl/$d"/*.c "$WATCH"/src/ovl/*/*.c "$WATCH"/src/c/*.h "$WATCH"/src/c/*.inc "$B/res_ids.h" "$BOT/src/pebble.h"; do [ "$f" -nt "$so" ] && need=1; done
  if [ $need = 1 ]; then
    gcc $CFLAGS -fPIC -shared -Wno-format-security -Wno-format-truncation -o "$so" $srcs
  fi
done

# 3. The loader: maps each overlay resource to its library, found next to the program
{
  echo '// generated by build.sh: each overlay is a shared library (dlopen per load, dlclose per free)'
  echo '#include "pd.h"'; echo '#include "ovl.h"'; echo '#include <dlfcn.h>'; echo '#include <stdio.h>'; echo '#include <string.h>'; echo '#include <unistd.h>'
  echo 'static struct { const OvlHeader *o; void *h; } s_open[16];'
  echo 'static const OvlHeader *open_ovl(const char *name) {'
  echo '  char dir[512] = "."; ssize_t n = readlink("/proc/self/exe", dir, sizeof dir - 1);'
  echo '  if (n > 0) { dir[n] = 0; char *s = strrchr(dir, 47); if (s) *s = 0; }'
  echo '  char so[600], sym[48]; snprintf(so, sizeof so, "%s/libovl_%s.so", dir, name); snprintf(sym, sizeof sym, "ovl_%s", name);'
  echo '  void *h = dlopen(so, RTLD_NOW | RTLD_LOCAL); if (!h) { fprintf(stderr, "%s\\n", dlerror()); return NULL; }'
  echo '  const OvlHeader *o = dlsym(h, sym);'
  echo '  for (int i = 0; i < 16; i++) if (!s_open[i].o) { s_open[i].o = o; s_open[i].h = h; break; }'
  echo '  return o;'
  echo '}'
  echo 'const OvlHeader *ovl_load(uint32_t res) {'
  for d in $OV; do U=$(echo $d | tr a-z A-Z); echo "  if (res == RESOURCE_ID_OVL_$U) return open_ovl(\"$d\");"; done
  echo '  return NULL;'; echo '}'
  echo 'void ovl_free(const OvlHeader *o) { for (int i = 0; i < 16; i++) if (s_open[i].o == o && o) { dlclose(s_open[i].h); s_open[i].o = NULL; return; } }'
} > "$B/host_ovl.c"

# 4. The program: the chosen main file + the watch's game core + host stand-ins for the watch's main.c
OUT=${OUT:-deepbot}; MAIN=${MAIN:-src/deepbot.c}
SRC="$WATCH/src/c/game.c $WATCH/src/c/items.c $WATCH/src/c/level_rt.c $WATCH/src/c/text.c $WATCH/src/c/ovl.c $B/host_ovl.c $BOT/src/hoststubs.c"
gcc $CFLAGS -rdynamic -o "$B/$OUT" "$MAIN" $SRC "$@" -ldl -lm
echo "built $B/$OUT"
