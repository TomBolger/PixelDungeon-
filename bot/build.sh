#!/bin/sh
# Build the dungeon bot (or a host test) against the watch game's own C sources.
#
#   ./build.sh                          -> build/deepbot   (the bot)
#   OUT=itemtest MAIN=tests/itemtest.c ./build.sh   -> build/itemtest
#   ./build.sh -DSOMETHING              extra compiler flags are passed through
#
# The game code is not copied: it is compiled straight from ../watch/src. Each code overlay becomes its own
# shared library (build/libovl_<name>.so) that is opened and closed like an overlay on the watch, so an
# overlay's static variables start from zero on every load, exactly as they do on the watch.
set -e
cd "$(dirname "$0")"
BOT=$(pwd)
WATCH=$(cd ../watch && pwd)
B=$BOT/build
EXTRA=""; FACEOVL=""; case " $* " in *" -DPD_FACE "*) B=$BOT/build/face; EXTRA="-DPD_FACE"; FACEOVL=$(cd "$BOT/../face/ovl" && ls);; esac   # (the face's own overlays, face/ovl, only in its build)
ovdir() { if [ -d "$WATCH/src/ovl/$1" ]; then echo "$WATCH/src/ovl/$1"; else echo "$BOT/../face/ovl/$1"; fi; }   # the watchface build: the overlays too are compiled with PD_FACE, in their own directory (build/face/facetest)
mkdir -p "$B"
CFLAGS="-std=c99 -O2 -DOVL_HOST -D_DEFAULT_SOURCE -DPD_DATA_DIR=\"$WATCH/resources/data\" -I$BOT/src -I$B -I$WATCH/src/c -Wall -Wno-unused-function -Wno-unused-parameter -Wno-format-truncation -Wno-misleading-indentation -Wno-unused-variable -Wno-unused-but-set-variable -Wno-parentheses $EXTRA"

# 1. RESOURCE_ID_* numbers in package.json order (rewritten only when they change: overlays depend on it)
python3 - "$WATCH/package.json" "$B/res_ids.h" $FACEOVL <<'PY'
import json, os, sys
m = json.load(open(sys.argv[1]))["pebble"]["resources"]["media"]
names = ["TEXT"] + [x["name"] for x in m if x["name"] != "TEXT"] + (["OVL_FSTAGE"] if len(sys.argv) > 3 else [])
t = "#pragma once\nenum { " + ", ".join(f"RESOURCE_ID_{n} = {i + 1}" for i, n in enumerate(names)) + " };\n"
if not os.path.exists(sys.argv[2]) or open(sys.argv[2]).read() != t: open(sys.argv[2], "w").write(t)
PY

# 2. One shared library per game overlay (UI-only overlays are not needed off the watch), rebuilt when a source changes
OV=""
for d in $(ls "$WATCH/src/ovl") $FACEOVL; do
  case $d in snd|ui|uiw|bag|sheet|fx) continue;; esac
  OV="$OV $d"
  so="$B/libovl_$d.so"; OD=$(ovdir $d); srcs=$(ls "$OD"/*.c)
  need=0; [ -f "$so" ] || need=1
  for f in "$OD"/*.c "$WATCH"/src/ovl/*/*.c "$WATCH"/src/c/*.h "$WATCH"/src/c/*.inc "$B/res_ids.h" "$BOT/src/pebble.h"; do [ "$f" -nt "$so" ] && need=1; done
  if [ $need = 1 ]; then
    gcc $CFLAGS -fPIC -shared -Wno-format-security -Wno-format-truncation -o "$so" $srcs
  fi
done

# 3. The loader: maps each overlay resource to its library, found next to the program.
# Speed (2026-11-13): a library is opened once and kept; when it is loaded with no other load of it open, its writable
# data (statics, .data/.bss, past the read-only-after-relocation part) is put back to how it was when first opened. That is
# what a dlclose and a fresh dlopen did (statics from zero on each load, as on the watch), without re-opening the file:
# dlopen/dlclose were ~10% of a search try. OVLSLOW=1: the old way.
{
  cat <<'CEOF'
// generated by build.sh: each overlay is a shared library, opened once; its writable data restored on each fresh load
#define _GNU_SOURCE
#include "pd.h"
#include "ovl.h"
#include <dlfcn.h>
#include <link.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
static struct { const OvlHeader *o; void *h; } s_open[16];
typedef struct { char name[24]; void *h; const OvlHeader *o; int open; int nseg; uint8_t *addr[4]; size_t len[4]; uint8_t *snap[4]; } OvlLib;
static OvlLib s_lib[40]; static int s_nlib, s_slow = -1;
static struct { const char *path; OvlLib *L; } s_cb;
static int phdr_cb(struct dl_phdr_info *in, size_t sz, void *d) {
  (void)sz; (void)d; if (!in->dlpi_name || strcmp(in->dlpi_name, s_cb.path)) return 0;
  uintptr_t r0 = 0, r1 = 0;
  for (int i = 0; i < in->dlpi_phnum; i++) if (in->dlpi_phdr[i].p_type == PT_GNU_RELRO) { r0 = in->dlpi_addr + in->dlpi_phdr[i].p_vaddr; r1 = r0 + in->dlpi_phdr[i].p_memsz; }
  OvlLib *L = s_cb.L;
  for (int i = 0; i < in->dlpi_phnum && L->nseg < 4; i++) { const ElfW(Phdr) *p = &in->dlpi_phdr[i]; if (p->p_type != PT_LOAD || !(p->p_flags & PF_W)) continue;
    uintptr_t a = in->dlpi_addr + p->p_vaddr, e = a + p->p_memsz; if (r1 > a && r0 <= a) a = r1 < e ? r1 : e; if (e <= a) continue;
    L->addr[L->nseg] = (uint8_t *)a; L->len[L->nseg] = e - a; L->snap[L->nseg] = malloc(e - a); memcpy(L->snap[L->nseg], (void *)a, e - a); L->nseg++; }
  return 1; }
static const OvlHeader *open_ovl(const char *name) {
  if (s_slow < 0) s_slow = getenv("OVLSLOW") != NULL;
  OvlLib *L = NULL; for (int i = 0; i < s_nlib; i++) if (!strcmp(s_lib[i].name, name)) L = &s_lib[i];
  if (L && !s_slow) { if (L->open++ == 0) for (int k = 0; k < L->nseg; k++) memcpy(L->addr[k], L->snap[k], L->len[k]); return L->o; }
  char dir[512] = "."; ssize_t n = readlink("/proc/self/exe", dir, sizeof dir - 1);
  if (n > 0) { dir[n] = 0; char *s = strrchr(dir, 47); if (s) *s = 0; }
  char so[600], sym[48]; snprintf(so, sizeof so, "%s/libovl_%s.so", dir, name); snprintf(sym, sizeof sym, "ovl_%s", name);
  void *h = dlopen(so, RTLD_NOW | RTLD_LOCAL); if (!h) { fprintf(stderr, "%s\n", dlerror()); return NULL; }
  const OvlHeader *o = dlsym(h, sym);
  if (s_slow) { for (int i = 0; i < 16; i++) if (!s_open[i].o) { s_open[i].o = o; s_open[i].h = h; break; } return o; }
  if (s_nlib >= 40) return o;
  L = &s_lib[s_nlib++]; memset(L, 0, sizeof *L); snprintf(L->name, sizeof L->name, "%s", name); L->h = h; L->o = o; L->open = 1;
  struct link_map *lm = NULL; dlinfo(h, RTLD_DI_LINKMAP, &lm); s_cb.path = lm ? lm->l_name : so; s_cb.L = L; dl_iterate_phdr(phdr_cb, NULL);
  return o;
}
void ovl_free(const OvlHeader *o) {
  if (!o) return;
  if (s_slow) { for (int i = 0; i < 16; i++) if (s_open[i].o == o) { dlclose(s_open[i].h); s_open[i].o = NULL; return; } return; }
  for (int i = 0; i < s_nlib; i++) if (s_lib[i].o == o) { if (s_lib[i].open > 0) s_lib[i].open--; return; }
}
CEOF
  echo 'const OvlHeader *ovl_load(uint32_t res) {'
  for d in $OV; do U=$(echo $d | tr a-z A-Z); echo "  if (res == RESOURCE_ID_OVL_$U) return open_ovl(\"$d\");"; done
  echo '  return NULL;'; echo '}'
} > "$B/host_ovl.c"

# 4. The program: the chosen main file + the watch's game core + host stand-ins for the watch's main.c
OUT=${OUT:-deepbot}; MAIN=${MAIN:-src/deepbot.c}
SRC="$WATCH/src/c/game.c $WATCH/src/c/items.c $WATCH/src/c/level_rt.c $WATCH/src/c/text.c $WATCH/src/c/ovl.c $B/host_ovl.c $BOT/src/hoststubs.c"
gcc $CFLAGS -rdynamic -o "$B/$OUT" "$MAIN" $SRC "$@" -ldl -lm
echo "built $B/$OUT"
