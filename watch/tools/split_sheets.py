"""Split the 8-bit item and tile sheets into small 4-bit sheets (0.6.5).

A sheet with more than 16 colours is stored at 8 bits per pixel. Each 16x16 sprite uses only a few
colours, so sprites are grouped into strips whose colours fit a 16-entry palette (15 + transparent).
That halves their RAM. Writes resources/images/<name>_<k>.png, src/c/sheets.auto.h (sprite -> strip
and cell) and the matching bitmap entries in package.json.

Usage: python3 tools/split_sheets.py   (after tools/convert_art.py)
"""
import json, os
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
IMG = os.path.join(ROOT, "resources", "images")
REGIONS = ["sewers", "prison", "caves", "city", "halls"]
SHEETS = [(f"tiles_{r}.png", f"tiles{i}", f"TILES{i}") for i, r in enumerate(REGIONS)]   # items: raw 4-bit sprites (0.8)
LIM = 15


def fold(cell, px, x0, y0):
    """Fold a sprite's rarest colours into their nearest until LIM remain."""
    counts = {}
    for y in range(y0, y0 + 16):
        for x in range(x0, x0 + 16):
            if px[x, y][3]: counts[px[x, y][:3]] = counts.get(px[x, y][:3], 0) + 1
    remap = {}
    while len(counts) > LIM:
        rare = min(counts, key=counts.get)
        n = counts.pop(rare)
        to = min(counts, key=lambda c: sum((a - b) ** 2 for a, b in zip(c, rare)))
        counts[to] += n
        for k, v in list(remap.items()):
            if v == rare: remap[k] = to
        remap[rare] = to
    for y in range(y0, y0 + 16):
        for x in range(x0, x0 + 16):
            r, g, b, a = px[x, y]
            if a and (r, g, b) in remap: px[x, y] = remap[(r, g, b)] + (255,)
    return frozenset(counts)


def split(src, base):
    im = Image.open(os.path.join(IMG, src)).convert("RGBA")
    px = im.load()
    cols, rows = im.width // 16, im.height // 16
    cells = [fold(None, px, (i % cols) * 16, (i // cols) * 16) for i in range(cols * rows)]
    groups = []                                   # [colours, [cell indices]]
    for i in sorted(range(len(cells)), key=lambda i: (-len(cells[i]), i)):
        best = None
        for g in groups:
            if base == "items" and len(g[1]) >= 6: continue      # 0.8: short item strips: a window loads only what it shows
            u = g[0] | cells[i]
            if len(u) <= LIM and (best is None or len(u) - len(g[0]) < len(best[0] | cells[i]) - len(best[0])): best = g
        if best is None: groups.append([cells[i], [i]])
        else: best[0] |= cells[i]; best[1].append(i)
    where = [0] * len(cells)
    for k, (_, idx) in enumerate(groups):
        idx.sort()
        strip = Image.new("RGBA", (16 * len(idx), 16))
        for j, i in enumerate(idx):
            strip.paste(im.crop(((i % cols) * 16, (i // cols) * 16, (i % cols) * 16 + 16, (i // cols) * 16 + 16)), (j * 16, 0))
            where[i] = k << 8 | j
        strip.save(os.path.join(IMG, f"{base}_{k}.png"))
    print(f"{src}: {len(cells)} sprites in {len(groups)} 4-bit strips, ~{len(cells) * 128 / 1024:.1f} KB (was {im.width * im.height / 1024:.1f} KB)")
    return len(groups), where


hdr = ["// generated by tools/split_sheets.py: sprite index -> (strip << 8 | cell); strips are 4-bit bitmaps", "#pragma once"]
pkg_path = os.path.join(ROOT, "package.json")
pkg = json.load(open(pkg_path))
media = pkg["pebble"]["resources"]["media"]
def raw_items():
    """resources/data/items_raw.bin: per sprite 16 palette bytes (Pebble ARGB8, 0 = clear) + 128 bytes of 4-bit pixels
    (high nibble first). main.c keeps a few of them in an LRU cache."""
    im = Image.open(os.path.join(IMG, "items_02.png")).convert("RGBA")
    px = im.load()
    cols, rows = im.width // 16, im.height // 16
    out = bytearray()
    for i in range(cols * rows):
        x0, y0 = (i % cols) * 16, (i // cols) * 16
        fold(None, px, x0, y0)
        pal = [None]
        for y in range(y0, y0 + 16):
            for x in range(x0, x0 + 16):
                if px[x, y][3] and px[x, y][:3] not in pal: pal.append(px[x, y][:3])
        assert len(pal) <= 16, (i, len(pal))
        out += bytes([0] + [0xC0 | (r // 85) << 4 | (g // 85) << 2 | (b // 85) for r, g, b in pal[1:]] + [0] * (16 - len(pal)))
        for y in range(y0, y0 + 16):
            for x in range(x0, x0 + 16, 2):
                a = 0 if not px[x, y][3] else pal.index(px[x, y][:3])
                b = 0 if not px[x + 1, y][3] else pal.index(px[x + 1, y][:3])
                out.append(a << 4 | b)
    open(os.path.join(ROOT, "resources", "data", "items_raw.bin"), "wb").write(out)
    print(f"items_raw.bin: {cols * rows} sprites, {len(out)} B")
    return cols * rows
n_items = raw_items()
hdr.append(f"#define N_ITEM_SPRITES {n_items}")
media[:] = [m for m in media if not m.get("name", "").startswith("IMAGE_ITEMS_")]
if not any(m["name"] == "ITEMS_RAW" for m in media):
    media.append({"type": "raw", "name": "ITEMS_RAW", "file": "data/items_raw.bin", "targetPlatforms": ["emery", "gabbro"]})
def raw_tile(px, x0, y0):
    """One 16x16 tile as 16 palette bytes + 128 bytes of 4-bit pixels. A tile with no clear pixel keeps its colours from
    index 0 (main.c: an opaque palette entry 0 means the tile can be copied without testing pixels)."""
    fold(None, px, x0, y0)
    clear = any(not px[x, y][3] for y in range(y0, y0 + 16) for x in range(x0, x0 + 16))
    pal = [None] if clear else []
    for y in range(y0, y0 + 16):
        for x in range(x0, x0 + 16):
            if px[x, y][3] and px[x, y][:3] not in pal: pal.append(px[x, y][:3])
    assert len(pal) <= 16
    out = bytearray(0 if c is None else 0xC0 | (c[0] // 85) << 4 | (c[1] // 85) << 2 | (c[2] // 85) for c in pal) + bytes(16 - len(pal))
    for y in range(y0, y0 + 16):
        for x in range(x0, x0 + 16, 2):
            a = 0 if not px[x, y][3] else pal.index(px[x, y][:3])
            b = 0 if not px[x + 1, y][3] else pal.index(px[x + 1, y][:3])
            out.append(a << 4 | b)
    return out
# 0.20: the tiles too are raw 4-bit cells (64 per region, 144 B each) in main.c's sprite cache, not strips held whole
tiles_raw = bytearray()
for r in REGIONS:
    im = Image.open(os.path.join(IMG, f"tiles_{r}.png")).convert("RGBA"); px = im.load()
    for i in range(64): tiles_raw += raw_tile(px, (i % 16) * 16, (i // 16) * 16)
open(os.path.join(ROOT, "resources", "data", "tiles_raw.bin"), "wb").write(tiles_raw)
print(f"tiles_raw.bin: {len(tiles_raw)} B")
