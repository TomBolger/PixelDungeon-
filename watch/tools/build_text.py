"""Pack the game's long texts into a resource (text.bin) and generate src/c/text_ids.h.

Source: resources/text/en.txt, one entry per line:  ID<TAB>text   (\\n for a line break)
Blank lines and lines starting with # are ignored. ID 0 (TX_NONE) is the empty string.
Binary: u16 count, u16 offset[count + 1] (from the start of the string area), then the bytes.
Code reads a text with txt(TX_ID) (main.c keeps a few rotating buffers).
"""
import os, struct, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ids, texts = ["NONE"], [""]
src = [l for f in ("en.txt", "mobs.txt") if os.path.exists(os.path.join(ROOT, "resources/text", f))
       for l in open(os.path.join(ROOT, "resources/text", f), encoding="utf8")]
for n, line in enumerate(src, 1):
    line = line.rstrip("\n")
    if not line or line.startswith("#"): continue
    k, _, v = line.partition("\t")
    if not _ or k in ids: sys.exit(f"en.txt:{n}: bad or duplicate entry {k!r}")
    ids.append(k); texts.append(v.replace("\\n", "\n"))
blob = b"".join(t.encode("utf8") for t in texts)
assert len(blob) < 65536
offs, o = [], 0
for t in texts: offs.append(o); o += len(t.encode("utf8"))
offs.append(o)
with open(os.path.join(ROOT, "resources/data/text.bin"), "wb") as f:
    f.write(struct.pack("<H", len(texts)) + struct.pack(f"<{len(offs)}H", *offs) + blob)
h = ["// generated by tools/build_text.py from resources/text/en.txt - do not edit", "#pragma once",
     f"#define TX_COUNT {len(ids)}"] + [f"#define TX_{k} {i}" for i, k in enumerate(ids)]
new = "\n".join(h) + "\n"
p = os.path.join(ROOT, "src/c/text_ids.h")
if not os.path.exists(p) or open(p).read() != new: open(p, "w").write(new)
print(f"text.bin: {len(texts)} texts, {len(blob)} bytes")
